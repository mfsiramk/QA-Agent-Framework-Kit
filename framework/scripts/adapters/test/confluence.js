/**
 * Confluence test-management adapter - test plans kept as Confluence pages.
 *
 * Layout (one page per requirement, under a parent page in a space):
 *   Page  "Test Plan - <requirement id> - <title>"           = the plan   (plan id = page id)
 *     h2  "<Suite / Subject>"                                 = a suite
 *     table  ID | Title | Priority | Preconditions | Steps | Expected Result | Test Data | Tags | AC Ref
 *                                                             = one row per test case
 * QA reviewers can edit the page directly - e.g. type "Automation" in the Tags cell - and
 * listTestCases() reads the page back, so Agent 3 sees their edits.
 *
 * Cases are collected in memory by createTestCase() and written in one page update by
 * finalize() (existing rows are kept; new rows are appended to their suite).
 *
 * config: baseUrl (…/wiki), deployment (cloud|server), spaceKey, parentPageId (optional)
 * secrets: cloud CONFLUENCE_EMAIL + CONFLUENCE_API_TOKEN · server CONFLUENCE_PAT
 *          (the same as the Confluence requirement-docs connector)
 */

const { request, basicAuth, bearer, htmlToText, atlassianUrl } = require('../../core/http.js');

const SERVICE = 'Confluence';
const COLS = ['ID', 'Title', 'Priority', 'Preconditions', 'Steps', 'Expected Result', 'Test Data', 'Tags', 'AC Ref'];
const pending = new Map(); // planId -> { title, url, version, suites: Map(name -> rows[]) }

function conn(ctx) {
  const c = ctx.config || {};
  const e = ctx.env || {};
  const baseUrl = atlassianUrl(c.baseUrl, 'confluence'); // Cloud: adds the /wiki that is often forgotten
  if (!baseUrl) throw new Error('Confluence: the Confluence URL is not configured. Fill it in the installer.');
  if (!c.spaceKey) throw new Error('Confluence: the space key for test plans is not configured.');
  if (String(c.deployment || 'cloud').toLowerCase() === 'server') {
    if (!e.CONFLUENCE_PAT) throw new Error('Confluence: CONFLUENCE_PAT is missing from .env.');
    return { baseUrl, space: c.spaceKey, parent: c.parentPageId, auth: bearer(e.CONFLUENCE_PAT) };
  }
  if (!e.CONFLUENCE_EMAIL || !e.CONFLUENCE_API_TOKEN) throw new Error('Confluence: CONFLUENCE_EMAIL / CONFLUENCE_API_TOKEN are missing from .env.');
  return { baseUrl, space: c.spaceKey, parent: c.parentPageId, auth: basicAuth(e.CONFLUENCE_EMAIL, e.CONFLUENCE_API_TOKEN) };
}

function call(ctx, path, opts = {}) {
  const c = conn(ctx);
  return request({ ...opts, url: `${c.baseUrl}/rest/api/${path}`, service: SERVICE, headers: { Authorization: c.auth, ...(opts.headers || {}) } });
}
const pageUrl = (ctx, id) => `${conn(ctx).baseUrl}/pages/viewpage.action?pageId=${id}`;

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const lines = (arr) => arr.map((x, i) => `${i + 1}. ${esc(x)}`).join('<br/>');

/** Storage-format HTML for the whole plan page. */
function render(plan) {
  const intro = `<p><strong>Requirement:</strong> ${plan.requirementLink || esc(plan.requirementId || '')}</p>`
    + '<p>Generated by QA Agent 2. Review the test cases below; to mark one for automation, add the automation tag (e.g. <em>Automation</em>) in its <strong>Tags</strong> cell. Agent 3 reads this page back.</p>';
  const suites = [...plan.suites.entries()].map(([name, rows]) => `<h2>${esc(name)}</h2><table><tbody><tr>${COLS.map((c) => `<th>${c}</th>`).join('')}</tr>${rows.map((r) => `<tr>${[
    esc(r.id), esc(r.title), esc(r.priority), esc(r.preconditions), lines(r.steps.map((s) => s.action)), lines(r.steps.map((s) => s.expected).filter(Boolean)), esc(r.testData), esc((r.tags || []).join(', ')), esc(r.acRef),
  ].map((v) => `<td>${v}</td>`).join('')}</tr>`).join('')}</tbody></table>`).join('');
  return intro + suites;
}

const cellText = (html) => htmlToText(String(html).replace(/<br\s*\/?>/gi, '\n').replace(/<\/p>\s*<p[^>]*>/gi, '\n'));
const splitLines = (t) => String(t).split(/\n+/).map((l) => l.replace(/^\s*\d+[.)]\s*/, '').trim()).filter(Boolean);

/** Parse the page body back into suites and test cases. */
function parse(storage) {
  const suites = new Map();
  const parts = String(storage || '').split(/(<h2[^>]*>[\s\S]*?<\/h2>)/i);
  let current = 'General';
  for (const part of parts) {
    if (/^<h2/i.test(part)) { current = htmlToText(part) || 'General'; if (!suites.has(current)) suites.set(current, []); continue; }
    for (const table of part.match(/<table[\s\S]*?<\/table>/gi) || []) {
      const rows = table.match(/<tr[\s\S]*?<\/tr>/gi) || [];
      if (!rows.length) continue;
      const head = (rows[0].match(/<t[hd][^>]*>[\s\S]*?<\/t[hd]>/gi) || []).map((c) => cellText(c).toLowerCase());
      const idx = (name) => head.findIndex((h) => h === name.toLowerCase());
      if (idx('title') < 0) continue;
      for (const row of rows.slice(1)) {
        const cells = (row.match(/<t[hd][^>]*>[\s\S]*?<\/t[hd]>/gi) || []).map(cellText);
        const get = (n) => (idx(n) >= 0 ? cells[idx(n)] || '' : '');
        if (!get('Title').trim()) continue;
        const actions = splitLines(get('Steps'));
        const expected = splitLines(get('Expected Result'));
        const steps = actions.length === expected.length ? actions.map((a, i) => ({ action: a, expected: expected[i] }))
          : actions.map((a, i) => ({ action: a, expected: i === actions.length - 1 ? expected.join('\n') : '' }));
        if (!suites.has(current)) suites.set(current, []);
        suites.get(current).push({ id: get('ID').trim(), title: get('Title').trim(), priority: get('Priority').trim() || 'Medium', preconditions: get('Preconditions'),
          steps: steps.length ? steps : [{ action: '', expected: expected.join('\n') }], testData: get('Test Data'), acRef: get('AC Ref'),
          tags: get('Tags').split(/[;,]/).map((t) => t.trim()).filter(Boolean) });
      }
    }
  }
  return suites;
}

async function getPage(ctx, id) {
  return call(ctx, `content/${encodeURIComponent(id)}?expand=body.storage,version,space`);
}

async function load(ctx, plan) {
  const id = String(plan.id || plan);
  if (pending.has(id)) return pending.get(id);
  const p = await getPage(ctx, id);
  const entry = { id, title: p.title, url: pageUrl(ctx, id), version: (p.version && p.version.number) || 1, suites: parse(p.body && p.body.storage && p.body.storage.value), requirementLink: '' };
  const m = String((p.body && p.body.storage && p.body.storage.value) || '').match(/<p><strong>Requirement:<\/strong>\s*([\s\S]*?)<\/p>/i);
  if (m) entry.requirementLink = m[1];
  pending.set(id, entry);
  return entry;
}

async function testConnection(ctx) {
  try {
    const c = conn(ctx);
    const s = await call(ctx, `space/${encodeURIComponent(c.space)}`);
    if (c.parent) await call(ctx, `content/${encodeURIComponent(c.parent)}`);
    return { ok: true, message: `Connected to Confluence space "${s.name || c.space}"${c.parent ? ' (parent page found)' : ''}.` };
  } catch (e) {
    return { ok: false, message: e.message, fix: /space key|404/i.test(e.message) ? 'Check the space key (shown in page addresses: …/spaces/KEY/…) and the parent page ID.' : 'Check the Confluence URL and the token in .env; the account needs "Add page" permission in the space.' };
  }
}

async function findPlans(ctx, requirementId) {
  const c = conn(ctx);
  const cql = `space="${c.space}" and type=page and title~"Test Plan ${String(requirementId).replace(/"/g, '')}"`;
  const r = await call(ctx, `content/search?cql=${encodeURIComponent(cql)}&limit=50`);
  const re = new RegExp(`^Test Plan - ${String(requirementId).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}( |$)`);
  return (r.results || []).filter((p) => re.test(p.title)).map((p) => ({ id: String(p.id), name: p.title, url: pageUrl(ctx, p.id) }));
}

async function createPlan(ctx, { name, requirement }) {
  const c = conn(ctx);
  const title = `Test Plan - ${name}`.slice(0, 255);
  const entry = { title, version: 1, suites: new Map(), requirementId: requirement && requirement.id,
    requirementLink: requirement && requirement.url && /^https?:/.test(requirement.url) ? `<a href="${esc(requirement.url)}">${esc(requirement.id)} - ${esc(requirement.title)}</a>` : esc(requirement ? `${requirement.id} - ${requirement.title}` : '') };
  const payload = { type: 'page', title, space: { key: c.space }, body: { storage: { value: render(entry), representation: 'storage' } } };
  if (c.parent) payload.ancestors = [{ id: String(c.parent) }];
  const page = await call(ctx, 'content', { method: 'POST', body: payload });
  entry.id = String(page.id);
  entry.url = pageUrl(ctx, entry.id);
  pending.set(entry.id, entry);
  return { id: entry.id, url: entry.url };
}

async function ensureSuite(ctx, plan, name) {
  const p = await load(ctx, plan);
  if (!p.suites.has(name)) p.suites.set(name, []);
  return { id: `${p.id}:${name}`, name };
}

async function listSuites(ctx, plan) {
  const p = await load(ctx, plan);
  return [...p.suites.keys()].map((name) => ({ id: `${p.id}:${name}`, name }));
}

async function createTestCase(ctx, { plan, suite, tc }) {
  const p = await load(ctx, plan);
  const name = (suite && suite.name) || tc.subject || 'General';
  if (!p.suites.has(name)) p.suites.set(name, []);
  const n = [...p.suites.values()].reduce((a, r) => a + r.length, 0) + 1;
  const id = tc.id || `TC-${String(n).padStart(3, '0')}`;
  p.suites.get(name).push({ id, title: tc.title, priority: tc.priority || 'Medium', preconditions: tc.preconditions || '', steps: tc.steps || [], testData: tc.testData || '', tags: tc.tags || [], acRef: tc.acRef || '' });
  p.dirty = true;
  return { id, url: p.url };
}

async function finalize(ctx, plan) {
  const id = String(plan.id || plan);
  const p = pending.get(id);
  if (!p || !p.dirty) return {};
  const c = conn(ctx);
  const current = await getPage(ctx, id); // re-read the version: someone may have edited the page meanwhile
  const latest = parse(current.body && current.body.storage && current.body.storage.value);
  for (const [name, rows] of p.suites) { // keep edits made on the page; add only rows not there yet
    const have = latest.get(name) || [];
    const titles = new Set(have.map((r) => r.title.toLowerCase()));
    latest.set(name, [...have, ...rows.filter((r) => !titles.has(String(r.title).toLowerCase()))]);
  }
  p.suites = latest;
  await call(ctx, `content/${id}`, { method: 'PUT', body: { id, type: 'page', title: current.title, space: { key: c.space }, version: { number: ((current.version && current.version.number) || 1) + 1 }, body: { storage: { value: render(p), representation: 'storage' } } } });
  p.dirty = false;
  return {};
}

async function listTestCases(ctx, plan) {
  const id = String(plan.id || plan);
  pending.delete(id); // always read the page fresh: QAs may have edited tags
  const p = await load(ctx, id);
  const out = [];
  for (const [suite, rows] of p.suites) rows.forEach((r) => out.push({ id: r.id || `${id}-${out.length + 1}`, title: r.title, priority: r.priority, steps: r.steps, tags: r.tags, suite, url: p.url }));
  return out;
}

