#!/usr/bin/env node
/**
 * AGENT 3 - build a Gherkin feature-file skeleton from the automation-tagged test
 * cases in a test plan. Every step is matched against steering/step-library.md:
 *   - match ≥ 0.55 → canonical step text reused (comment "# reused: <score>")
 *   - otherwise    → original wording kept, marked "# [NEW]" for the assistant to refine
 *
 *   node scripts/agents/agent3-generate-feature.js <testPlanId> [--requirement <workItemId>]
 *
 * Writes output/features/<workItemId>/<Name>.feature + <Name>.reuse.json
 * Exit 2 = NO AUTOMATION TAG FOUND, 4 = CREDENTIALS_INVALID, 1 = failure.
 */

const fs = require('fs');
const path = require('path');
const { loadConfig, taskAdapter, testAdapter, outDir } = require('../core/config');
const { preflight } = require('../core/preflight');
const { arg, positional, bestMatch, exitWith } = require('../core/util');

function loadLibrary(root) {
  const f = path.join(root, 'steering', 'step-library.md');
  if (!fs.existsSync(f)) return [];
  const out = [];
  const fence = /```(?:gherkin|text)?\n([\s\S]*?)```/g;
  let m;
  while ((m = fence.exec(fs.readFileSync(f, 'utf8')))) {
    m[1].split('\n').map((l) => l.trim()).filter(Boolean).forEach((l) => out.push(l.replace(/^(Given|When|Then|And|But)\s+/, '')));
  }
  return [...new Set(out)];
}

function findRequirementForPlan(root, planId) {
  const dir = path.join(root, 'output', 'temp');
  if (!fs.existsSync(dir)) return null;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('-agent2-result.json'))) {
    try { const r = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); if (String(r.plan?.id) === String(planId)) return r.workItemId; } catch { /* ignore */ }
  }
  return null;
}

const pascal = (s) => String(s).replace(/[^a-zA-Z0-9 ]+/g, ' ').split(/\s+/).filter(Boolean).slice(0, 6).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const tagSafe = (s) => String(s).replace(/[^A-Za-z0-9_-]+/g, '_');

(async () => {
  const [planId] = positional();
  if (!planId) exitWith(1, 'Usage: node scripts/agents/agent3-generate-feature.js <testPlanId> [--requirement <workItemId>]');
  const cfg = loadConfig();
  if (!cfg.modules.agent3 || cfg.automation?.status === 'none') exitWith(1, 'ℹ️  Agent 3 is not enabled for this installation (no automation in scope). Re-run the installer to enable it.');
  const tag = cfg.testManagement.automationTag || 'Automation';
  await preflight(cfg, ['task', 'test']);
  const test = testAdapter(cfg);
  const task = taskAdapter(cfg);

  const all = await test.adapter.listTestCases(test.ctx, { id: String(planId) });
  const tagged = all.filter((t) => (t.tags || []).some((x) => x.toLowerCase() === tag.toLowerCase()));
  if (!tagged.length) {
    exitWith(2, 'NO AUTOMATION TAG FOUND', [
      `Test plan ${planId} has ${all.length} test case(s) but none carry the "${tag}" tag.`,
      'Ask the QA to add the tag to the test cases that should be automated (in the test tool), then re-run.',
    ]);
  }

  let reqId = arg('requirement');
  if (!reqId || reqId === true) reqId = findRequirementForPlan(cfg.root, planId) || planId;
  let requirement = { id: reqId, title: `Test plan ${planId}` };
  try { requirement = await task.adapter.getWorkItem(task.ctx, reqId); } catch { /* plan-only mode */ }

  const library = loadLibrary(cfg.root);
  const short = tagSafe(cfg.organization?.shortCode || 'QA');
  const featureName = pascal(requirement.title) || `Plan${planId}`;
  const out = [];
  const reuse = [];
  out.push(`@${short} @WI_${tagSafe(requirement.id)} @Plan_${tagSafe(planId)}`);
  out.push(`Feature: ${requirement.title}`);
  out.push(`  # Source: ${requirement.url || requirement.id} · Test plan ${planId}`);
  out.push(`  # Generated by QA Agent 3 - review every "# [NEW]" step before approving.`);
  out.push('');

  let n = 0;
  for (const tc of tagged) {
    n++;
    out.push(`  @TC_${short}_${tagSafe(requirement.id)}_${String(n).padStart(3, '0')} @${tagSafe(tc.priority || 'Medium')} @${tagSafe(tc.suite || 'General')}`);
    out.push(`  Scenario: ${tc.title}`);
    out.push(`    # Test case: ${tc.id}${tc.url ? ` ${tc.url}` : ''}`);
    let first = true;
    let lastKw = null;
    for (const s of tc.steps || []) {
      for (const [text, isExpected] of [[s.action, false], [s.expected, true]]) {
        if (!text || !String(text).trim()) continue;
        const clean = String(text).replace(/\s+/g, ' ').trim();
        const m = library.length ? bestMatch(clean, library) : { score: 0 };
        const reused = m.score >= 0.55;
        const stepText = reused ? m.pattern : clean;
        const desired = isExpected ? 'Then' : (first ? 'Given' : 'When');
        const kw = desired === lastKw ? 'And' : desired;
        lastKw = desired;
        first = false;
        out.push(`    ${kw} ${stepText}${reused ? `  # reused: ${Math.round(m.score * 100)}%` : '  # [NEW]'}`);
        reuse.push({ tc: tc.id, original: clean, used: stepText, reused, score: Math.round((m.score || 0) * 100) });
      }
    }
    out.push('');
  }

  const dir = outDir('features', tagSafe(requirement.id));
  const file = path.join(dir, `${featureName}.feature`);
  fs.writeFileSync(file, out.join('\n'));
  const reusedCount = reuse.filter((r) => r.reused).length;
  fs.writeFileSync(path.join(dir, `${featureName}.reuse.json`), JSON.stringify({ planId, requirement: requirement.id, scenarios: tagged.length, steps: reuse.length, reused: reusedCount, details: reuse }, null, 2));

  console.log('\n✅ Feature skeleton generated');
  console.log(`   Scenarios:     ${tagged.length} (of ${all.length} test cases; only "${tag}"-tagged)`);
  console.log(`   Steps reused:  ${reusedCount}/${reuse.length} (${reuse.length ? Math.round((reusedCount / reuse.length) * 100) : 0}%)${library.length ? '' : '  ⚠️ no step library - run npm run step-library'}`);
  console.log(`   [NEW] steps:   ${reuse.length - reusedCount}`);
  console.log(`   File:          ${path.relative(cfg.root, file)}`);
  console.log('\n➡️  Refine the [NEW] steps per agents/agent3-feature-file-generator.md, then ask the user to review and say "Approved".');
})().catch((e) => { console.error(`❌ ${e.message}`); process.exit(1); });
