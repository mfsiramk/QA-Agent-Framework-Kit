function commonPrinciples(d) {
  return `# Common Principles (all agents)

1. **Each source has a job** (see the table in the Agent 1 file): the ${d.task.vocab.item} defines **scope** (what is being built now, its AC)${d.docs.id !== 'none' ? '; requirement documents define the **business rules** (validations, roles, calculations, edge cases)' : ''}${d.design.id !== 'none' ? '; designs define the **UI** (labels, states, messages, layout)' : ''}; comments carry the **latest decisions**; code changes show **what actually changed** (regression areas). When two sources disagree, never pick one silently - record a clarification question.
2. **Never invent business rules.** If the AC is ambiguous, record a clarification question (\`clarificationQuestions[]\`) instead of guessing.
3. **Test case quality**: one behaviour per test case; atomic numbered steps (one action each); concrete test data (no "valid data"); every expected result observable and specific.
4. **Priority scale**: Critical (blocks release / money / data loss) · High (core journey) · Medium (secondary path) · Low (cosmetic).
5. **Coverage**: every AC line gets at least one positive and, where meaningful, one negative/boundary test. \`acRef\` must quote the AC text it covers.
6. **Human in the loop**: the QA-curated Excel is the source of truth. Fewer rows than generated = intentional curation, never a bug.
7. **Summaries only in chat**: counts + file paths.
8. **Vocabulary for this installation**: ${d.task.vocab.item} (task tool), ${d.test.vocab.plan} / ${d.test.vocab.suite} / ${d.test.vocab.case} (test tool), release = ${d.task.vocab.release}.
`;
}

